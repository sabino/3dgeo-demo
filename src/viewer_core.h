/* Unsigned subtraction handles VBlank counter wrap. Drop long debugger stalls
 * instead of applying a large, disorienting rotation on resume. */
static inline uint16_t viewer_elapsed_ticks(uint16_t now, uint16_t previous) {
    uint16_t elapsed = (uint16_t)(now - previous);
    return elapsed > 8 ? 8 : elapsed;
}
